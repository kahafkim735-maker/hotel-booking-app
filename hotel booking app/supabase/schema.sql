create table if not exists public.hotels (
  id bigint generated by default as identity primary key,
  name text not null,
  location text not null,
  country text,
  price numeric not null default 0,
  rating numeric default 0,
  reviews integer default 0,
  image text,
  description text,
  amenities text[],
  category text,
  badge text
);

create table if not exists public.bookings (
  id text primary key,
  hotel_id bigint,
  hotel_name text not null,
  location text,
  guest_name text not null,
  guest_email text not null,
  guest_phone text,
  special_requests text,
  check_in date not null,
  check_out date not null,
  guests integer not null default 1,
  nights integer not null default 1,
  total_price numeric not null default 0,
  status text default 'Confirmed',
  created_at timestamptz default now()
);

alter table public.hotels enable row level security;
alter table public.bookings enable row level security;

create policy "Allow public read access to hotels"
on public.hotels for select using (true);

create policy "Allow public insert access to bookings"
on public.bookings for insert with check (true);

create policy "Allow public read access to bookings"
on public.bookings for select using (true);

create policy "Allow public update access to bookings"
on public.bookings for update using (true) with check (true);

create policy "Allow public delete access to bookings"
on public.bookings for delete using (true);

